import { chromium, expect } from '@playwright/test';
const browser=await chromium.launch({headless:true,channel:'msedge'});
const page=await browser.newPage({viewport:{width:1440,height:810}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
try {
 await page.goto('http://127.0.0.1:5173/#dashboard');
 await page.locator('[data-name="Nav / Suspected vs Confirmed"]').click();
 await expect(page.getByRole('heading',{name:'Suspected vs Confirmed Disease',exact:true})).toBeVisible();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await expect(page.getByRole('table',{name:'Confirmed diagnoses'}).locator('tbody tr')).toHaveCount(3);
 await expect(page.locator('[data-name="Nav / Suspected vs Confirmed"]')).toHaveAttribute('data-active','true');
 await page.screenshot({path:'artifacts/comparison.png'});
 const download=page.waitForEvent('download');
 await page.locator('[data-name="Button / secondary / Export"]').click();
 expect((await download).suggestedFilename()).toBe('tealeaf-comparison.csv');
 await page.locator('[data-name="Button / secondary / Filters"]').click();
 await expect(page.getByRole('heading',{name:'Reporting Filters',exact:true})).toBeVisible();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.getByRole('button',{name:'Reset',exact:true}).click();
 await expect(page.getByLabel('Division',{exact:true})).toBeDisabled();
 await expect(page.getByRole('table',{name:'Filtered observations'}).locator('tbody tr')).toHaveCount(6);
 await page.screenshot({path:'artifacts/filters.png'});
 await page.getByLabel('Estate',{exact:true}).selectOption('Highland');
 await expect(page.getByLabel('Division',{exact:true})).toBeEnabled();
 await page.getByLabel('Division',{exact:true}).selectOption('DIV-002');
 await page.getByLabel('Period',{exact:true}).selectOption('7');
 await page.getByRole('button',{name:'Apply filters',exact:true}).click();
 await expect(page.getByRole('heading',{name:'No observations in this selection'})).toBeVisible();
 await page.screenshot({path:'artifacts/filters-empty.png'});
 await page.reload();
 await expect(page.getByLabel('Division',{exact:true})).toHaveValue('DIV-002');
 await expect(page.getByRole('heading',{name:'No observations in this selection'})).toBeVisible();
 await page.getByLabel('Estate',{exact:true}).selectOption('Riverbend');
 await expect(page.getByLabel('Division',{exact:true})).toHaveValue('all');
 await page.getByLabel('Period',{exact:true}).selectOption('30');
 await page.getByLabel('Submitted',{exact:true}).uncheck();
 await page.getByLabel('Show both separately',{exact:true}).check();
 await page.getByRole('button',{name:'Apply filters',exact:true}).click();
 const table=page.getByRole('table',{name:'Filtered observations'});
 await expect(table.locator('tbody tr')).toHaveCount(3);
 await expect(table.getByRole('columnheader',{name:/^Submitted$/i})).toHaveCount(0);
 await expect(table.getByRole('columnheader',{name:/Expert-confirmed/i})).toBeVisible();
 await expect(table.getByRole('columnheader',{name:/Suspected disease/i})).toBeVisible();
 await page.getByRole('button',{name:'Reset',exact:true}).click();
 await expect(page.getByLabel('Estate',{exact:true})).toHaveValue('all');
 await expect(page.getByLabel('Submitted',{exact:true})).toBeChecked();
 await expect(table.locator('tbody tr')).toHaveCount(6);
 await page.locator('[data-name="Nav / Suspected vs Confirmed"]').click();
 await expect(page.getByRole('heading',{name:'Weekly counts'})).toBeVisible();
 await page.goBack();
 await expect(page.getByRole('heading',{name:'Reporting Filters',exact:true})).toBeVisible();
 await page.locator('[data-name="Nav / Analytics Dashboard"]').click();
 await page.locator('[data-name="Nav / Reporting Filters"]').click();
 await expect(page.getByRole('heading',{name:'Reporting Filters',exact:true})).toBeVisible();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 expect(errors).toEqual([]);
 console.log('Comparison and filters: navigation, no placeholders, diagnosis table, export, dependent selectors, Apply, empty results, persistence, status columns, measures, Reset and browser history passed.');
} finally { await browser.close(); }
